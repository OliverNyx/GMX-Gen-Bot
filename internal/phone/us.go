// E164 returns a random US number in +1XXXXXXXXXX form (HAR used +12163840118).
func E164(r *rand.Rand) string {
	ac := areaCodes[r.Intn(len(areaCodes))]
	// NXX: central office code; first digit 2-9, avoid 555 (fictional).
	exchange := 200 + r.Intn(800)
	if exchange == 555 {
		exchange = 556
	}
	line := 1000 + r.Intn(9000)
	return fmt.Sprintf("+1%d%03d%04d", ac, exchange, line)
}
